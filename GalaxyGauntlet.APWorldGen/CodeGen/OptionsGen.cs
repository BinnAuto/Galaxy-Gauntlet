using GalaxyGauntlet.Common;

namespace GalaxyGauntlet.APWorldGen.CodeGen
{
    public static partial class APWorldCodeGen
    {
        public static void GenerateOptionClass()
        {
            FileLogger.QuietLogMessage("Creating options.py...");
            List<string> fileLines = [
                "from dataclasses import dataclass",
                "from Options import Choice, DeathLink, PerGameCommonOptions, Range, Toggle",
                "",
                "class PlayerSpriteOption(Choice):",
                "    \"\"\"",
                "    Determines the sprite to use for Chip when displaying the player character.",
                "    \"\"\"",
                "    display_name = \"Player Sprite\"",
                "    option_Chip = 0",
                "    option_Teeth = 1",
                "    option_Tank = 2",
                "    option_Glider = 3",
                "    option_Bug = 4",
                "    option_Paramecium = 5",
                "    option_Fireball = 6",
                "    option_Walker = 7",
                "",
                "class MaximumChipLocationsPerLevel(Range):",
                "    \"\"\"",
                "    Specifies the maximum amount of chips in a level that can be used as Archipelago " +
                "    locations. Set this value to 0 to disable using chip items as locations.",
                "    \"\"\"",
                "    display_name = \"Maximum Chip Locations Per Level\"",
                "    range_start = 0",
                "    range_end = 15",
                "    default = 4",
                "",
                "class ProportionOfFillerAsUsefulItems(Range):",
                "    \"\"\"",
                "    Specifies the proportion of remaining filler items that should be used for useful items.",
                "    Set this value to 0 to disable useful items.",
                "    \"\"\"",
                "    display_name = \"Proportion of Filler as Useful Items\"",
                "    range_start = 0",
                "    range_end = 100",
                "    default = 0",
                "",
                "class ProportionOfFillerAsTraps(Range):",
                "    \"\"\"",
                "    Specifies the proportion of remaining filler items (after adding useful items) that should be used for trap items.",
                "    Set this value to 0 to disable trap items.",
                "    \"\"\"",
                "    display_name = \"Proportion of Filler as Trap Items\"",
                "    range_start = 0",
                "    range_end = 100",
                "    default = 0",
                "",
                "class LevelCompletionGoal(Range):",
                "    \"\"\"",
                "    Specifies the minimum amount of levels to complete to reach the goal condition.",
                "    Set this value to 0 to disable this as a goal.",
                "    \"\"\"",
                "    display_name = \"Level Completion Requirement\"",
                "    range_start = 0",
                $"    range_end = {LevelNames.Count}",
                "    default = 0",
                "",
                "class ScoreGoal(Range):",
                "    \"\"\"",
                "    Specifies the minimum score requirement to reach the goal condition.",
                "    Set this value to 0 to disable this as a goal.",
                "    \"\"\"",
                "    display_name = \"Goal Score Requirement\"",
                "    range_start = 0",
                $"    range_end = {MaximumScore}",
                "    default = 0",
                "",
                "class AddExtendedScoreChecks(Toggle):",
                "    \"\"\"",
                "    Add additional checks for higher score milestones.",
                "    \"\"\"",
                "    display_name = \"Include Extended Score Checks\"",
                "",
                "class CruelTimeItems(Toggle):",
                "    \"\"\"",
                "    If active, untimed levels will be affected by Time Bonus and Time Penalty items",
                "    received through Archipelago, effectively an auto-death.",
                "    \"\"\"",
                "    display_name = \"Cruel Time Items\"",
                "",
                "class ChipLocationDisplayOption(Choice):",
                "    \"\"\"",
                "    Determines how chip locations should appear in game.",
                "     - Actual: The icon for uncollected items appears according to the item's type. Chips that are not locations display as regular chips.",
                "     - Vague: All unvisited Archipelago locations appear as Helpful items. Chips that are not locations display as regular chips.",
                "     - Hidden: All chips display as regular chips, whether they are Archipelago locations or not.",
                "    \"\"\"",
                "    display_name = \"Chip Location Display\"",
                "    option_True = 0",
                "    option_Vague = 1",
                "    option_Hidden = 2",
                "",
                "class DeathLinkSendProbability(Range):",
                "    \"\"\"",
                "    Determines the odds (out of 100) that a death ingame will send out a death link message to other players.",
                "    Set this value to 0 to disable sending death link messages.",
                "    Set this value to 100 to enable traditional death link behavior.",
                "    \"\"\"",
                "    display_name = \"Death Link Send Probability\"",
                "    range_start = 0",
                "    range_end = 100",
                "    default = 0",
                "",
                "class DeathLinkReceiveProbability(Range):",
                "    \"\"\"",
                "    Determines the odds (out of 100) that death link message received from another player will kill you.",
                "    Set this value to 0 to be immune to death link from others.",
                "    Set this value to 100 to enable traditional death link behavior.",
                "    \"\"\"",
                "    display_name = \"Death Link Receive Probability\"",
                "    range_start = 0",
                "    range_end = 100",
                "    default = 0",
                ""
            ];
            fileLines.AddRange([
                "@dataclass",
                $"class {ClassPrefix}Options(PerGameCommonOptions):",
                $"    {GGConstants.Archipelago.SlotDataKeys.PlayerSprite}: PlayerSpriteOption",
                $"    proportion_of_filler_as_useful_items: ProportionOfFillerAsUsefulItems",
                $"    proportion_of_filler_as_traps: ProportionOfFillerAsTraps",
                $"    {GGConstants.Archipelago.SlotDataKeys.ScoreGoal}: ScoreGoal",
                $"    {GGConstants.Archipelago.SlotDataKeys.LevelCompletionGoal}: LevelCompletionGoal",
                $"    {GGConstants.Archipelago.SlotDataKeys.DeathLinkSendProbability}: DeathLinkSendProbability",
                $"    {GGConstants.Archipelago.SlotDataKeys.DeathLinkReceiveProbability}: DeathLinkReceiveProbability",
                $"    {GGConstants.Archipelago.SlotDataKeys.CruelTimeItems}: CruelTimeItems",
                $"    {GGConstants.Archipelago.SlotDataKeys.ChipLocationDisplay}: ChipLocationDisplayOption",
                $"    {GGConstants.Archipelago.SlotDataKeys.MaximumChipLocationsPerLevel}: MaximumChipLocationsPerLevel"
            ]);
            if(IncludeExtendedScoreChecks)
            {
                fileLines.Add(
                "    include_extended_score_checks: AddExtendedScoreChecks"
                );
            }

            WriteFileContents("options.py", fileLines);
            FileLogger.QuietLogMessage("File created");
        }
    }
}
